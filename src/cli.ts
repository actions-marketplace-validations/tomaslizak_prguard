#!/usr/bin/env node
import { Command } from 'commander';
import { buildAuditReport, RepoAuditReport, ScoredPR } from './analyzer.js';
import { fetchOpenPRs } from './github.js';
import * as fs from 'node:fs';

function verdictBadge(verdict: ScoredPR['verdict']): string {
  switch (verdict) {
    case 'RECOMMENDED_WINNER':
      return '🏆 RECOMMENDED WINNER';
    case 'VALID_CONTENDER':
      return '✅ VALID CONTENDER';
    case 'NEEDS_SCRUTINY':
      return '⚠️ NEEDS SCRUTINY';
    case 'LIKELY_SLOP':
      return '🚨 LIKELY SLOP';
  }
}

export function formatMarkdownReport(report: RepoAuditReport): string {
  const lines: string[] = [];
  lines.push(`# 🛡️ PRGuard Anti-Slop & Bounty Triage Report: \`${report.repo}\``);
  lines.push(`*Scanned at: ${report.scannedAt}*`);
  lines.push('');
  lines.push('## 📊 Executive Summary');
  lines.push(`- **Total Open PRs Analyzed:** ${report.totalOpenPRs}`);
  lines.push(`- **Competing PRs in Multi-PR Issue Clusters:** ${report.competingPRCount}`);
  lines.push(`- **Flagged as Likely Bot/AI Slop:** ${report.likelySlopCount}`);
  lines.push(`- **Estimated Maintainer Review Time Saved:** ~${report.estimatedMaintainerHoursSaved} hours`);
  lines.push('');

  for (const cluster of report.clusters) {
    if (cluster.issueNumber === 'UNLINKED') {
      lines.push(`## 📂 Unlinked Pull Requests (${cluster.totalPRs})`);
    } else {
      lines.push(
        `## 🎯 Issue #${cluster.issueNumber} — ${cluster.totalPRs} Competing Pull Request(s)`
      );
      if (cluster.recommendedWinner) {
        lines.push(
          `> **🏆 Top Recommendation:** **PR #${cluster.recommendedWinner.pr.number}** by \`@${cluster.recommendedWinner.pr.user}\` (Quality Score: **${cluster.recommendedWinner.totalScore}/100**, CI: \`${cluster.recommendedWinner.pr.ciState}\`)`
        );
      }
    }
    lines.push('');
    lines.push('| Rank | PR | Author | Score | Verdict | CI | Diff (+ / -) | Key Signals |');
    lines.push('| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |');

    cluster.rankedPRs.forEach((item, idx) => {
      const sigSummary =
        item.signals
          .map((s) => `${s.points > 0 ? '+' : ''}${s.points} \`${s.code}\``)
          .join(', ') || 'Baseline';
      lines.push(
        `| #${idx + 1} | [#${item.pr.number}](${item.pr.htmlUrl}) | \`@${item.pr.user}\` | **${item.totalScore}/100** | ${verdictBadge(item.verdict)} | \`${item.pr.ciState}\` | +${item.pr.additions} / -${item.pr.deletions} (${item.pr.changedFiles}f) | ${sigSummary} |`
      );
    });
    lines.push('');
  }

  lines.push('---');
  lines.push('*Generated by **PRGuard** — Autonomous Anti-Slop & Bounty Triage Engine.*');
  return lines.join('\n');
}

const program = new Command();
program
  .name('prguard')
  .description('Anti-Slop PR Triage, Duplicate Cluster & Bounty Verification Engine')
  .version('1.0.0');

program
  .command('scan <repo>')
  .description('Scan open Pull Requests in a GitHub repository (owner/repo)')
  .option('-l, --limit <number>', 'Maximum open PRs to analyze', '40')
  .option('-o, --output <path>', 'Save Markdown report to file')
  .option('--json <path>', 'Save raw JSON audit data to file')
  .action((repo: string, opts: { limit: string; output?: string; json?: string }) => {
    const limit = parseInt(opts.limit, 10) || 40;
    console.log(`🔍 Scanning up to ${limit} open PRs in ${repo}...`);
    const prs = fetchOpenPRs(repo, limit);
    const report = buildAuditReport(repo, prs);
    const md = formatMarkdownReport(report);

    if (opts.output) {
      fs.writeFileSync(opts.output, md, 'utf-8');
      console.log(`✅ Markdown report written to ${opts.output}`);
    } else {
      console.log('\n' + md);
    }

    if (opts.json) {
      fs.writeFileSync(opts.json, JSON.stringify(report, null, 2), 'utf-8');
      console.log(`✅ JSON report written to ${opts.json}`);
    }
  });

program.parse();
